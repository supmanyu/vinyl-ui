// Generates dist/{index.js,index.d.ts,palette.css,web.css,native.css,shadcn.json} from src/tokens.ts.
import { mkdirSync, writeFileSync } from 'node:fs';
import { clampChroma, formatHex, oklch } from 'culori';
import * as t from '../src/tokens.ts';

const STEPS = {
  50: 0.97,
  100: 0.93,
  200: 0.87,
  300: 0.8,
  400: 0.72,
  500: 0.64,
  600: 0.56,
  700: 0.48,
  800: 0.4,
  900: 0.3,
  950: 0.2,
} as const;

const ramp = (hex: string) => {
  const base = oklch(hex);
  if (!base) throw new Error(`bad colour ${hex}`);
  return Object.fromEntries(
    Object.entries(STEPS).map(([step, l]) => {
      // Fade chroma toward the extremes so 50/950 stay usable as tints/shades.
      const c = (base.c ?? 0) * (1 - Math.abs(l - base.l) * 0.9);
      return [
        step,
        formatHex(clampChroma({ mode: 'oklch', l, c, h: base.h }, 'oklch')).toUpperCase(),
      ];
    }),
  ) as Record<keyof typeof STEPS, string>;
};

const ramps = Object.fromEntries(Object.entries(t.palette).map(([k, v]) => [k, ramp(v)])) as Record<
  keyof typeof t.palette,
  Record<keyof typeof STEPS, string>
>;

const resolve = (v: string): string => {
  if (v.startsWith('#')) return v;
  const [name, step] = v.split(/-(?=\d+$)/) as [keyof typeof t.palette, string | undefined];
  const out = step ? ramps[name]?.[Number(step) as keyof typeof STEPS] : t.palette[name];
  if (!out) throw new Error(`unknown colour reference "${v}"`);
  return out;
};
const resolveTheme = (theme: Record<string, string>) =>
  Object.fromEntries(Object.entries(theme).map(([k, v]) => [k, resolve(v)]));

const themes = { dark: resolveTheme(t.dark), light: resolveTheme(t.light) };
const semantic = Object.keys(t.dark);
const nativeRadii = { sm: '2px', md: '4px', lg: '6px', xl: '8px' };

const decls = (vars: Record<string, string>, prefix = '', indent = '  ') =>
  Object.entries(vars)
    .map(([k, v]) => `${indent}--${prefix}${k}: ${v};`)
    .join('\n');

const paletteVars: Record<string, string> = { ...t.effects };
for (const [name, hex] of Object.entries(t.palette)) {
  paletteVars[name] = hex;
  for (const [step, val] of Object.entries(ramps[name as keyof typeof ramps]))
    paletteVars[`${name}-${step}`] = val;
}

const header = '/* Generated by @vinyl-ui/tokens — do not edit. */\n';

const gradients = Object.fromEntries(
  Object.entries(t.gradients).map(([k, g]) => [k, { angle: g.angle, stops: g.stops.map(resolve) }]),
) as Record<keyof typeof t.gradients, { angle: number; stops: string[] }>;

const gradientVars = Object.fromEntries(
  Object.entries(gradients).map(([k, g]) => [
    k,
    `linear-gradient(${g.angle}deg, ${g.stops.join(', ')})`,
  ]),
);

const paletteCss = `${header}@theme static {
${decls(paletteVars, 'color-')}
${decls(t.fonts, 'font-')}
${decls(t.shadows, 'shadow-')}
}

:root {
${decls(gradientVars, 'gradient-')}
}
`;

const webCss = `${header}@import "./palette.css";

@custom-variant dark (&:is(.dark *));

:root {
  --radius: ${t.radius};
${decls(themes.light)}
}

.dark {
${decls(themes.dark)}
}

@theme inline {
${semantic.map((k) => `  --color-${k}: var(--${k});`).join('\n')}
  --radius-sm: calc(var(--radius) - 2px);
  --radius-md: var(--radius);
  --radius-lg: calc(var(--radius) + 2px);
  --radius-xl: calc(var(--radius) + 4px);
}

@layer base {
  * {
    @apply border-border outline-ring/50;
  }
  body {
    @apply bg-background text-foreground;
  }
}
`;

const nativeCss = `${header}@theme {
${decls(paletteVars, 'color-')}
${decls(nativeRadii, 'radius-')}
}

@layer theme {
  :root {
    @variant dark {
${decls(themes.dark, 'color-', '      ')}
    }
    @variant light {
${decls(themes.light, 'color-', '      ')}
    }
  }
}
`;

// cssVars for the shadcn `theme` registry item (palette comes via @import of palette.css).
const shadcn = {
  light: { radius: t.radius, ...themes.light },
  dark: themes.dark,
};

const js = {
  palette: t.palette,
  ramps,
  themes,
  effects: t.effects,
  gradients,
  smpte: t.smpte,
  radius: t.radius,
  fonts: t.fonts,
};

mkdirSync('dist', { recursive: true });
writeFileSync('dist/palette.css', paletteCss);
writeFileSync('dist/web.css', webCss);
writeFileSync('dist/native.css', nativeCss);
writeFileSync('dist/shadcn.json', `${JSON.stringify(shadcn, null, 2)}\n`);
writeFileSync(
  'dist/index.js',
  `${Object.entries(js)
    .map(([k, v]) => `export const ${k} = ${JSON.stringify(v, null, 2)};`)
    .join('\n')}\n`,
);
writeFileSync(
  'dist/index.d.ts',
  Object.entries(js)
    .map(([k, v]) => `export declare const ${k}: ${JSON.stringify(v, null, 2)};`)
    .join('\n') +
    '\nexport type ThemeName = keyof typeof themes;\nexport type SemanticToken = keyof (typeof themes)["dark"];\n',
);
console.log(
  `tokens: ${Object.keys(paletteVars).length} palette vars, ${semantic.length} semantic tokens`,
);
